"""Build failure and recovery tests: real core and P&ID adapter, FAKE Blender subprocess.

``FakeBlender`` replaces only the Blender subprocess. It receives the real
argument array, plans the scene with the pure-Python Blender planner, writes
that plan's manifest, and writes a placeholder blend file. It is not Blender
generation; ``tests/test_integration.py`` holds the opt-in actual Blender check.
"""

from __future__ import annotations

import argparse
import copy
import fcntl
import json
import os
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from skid.adapters.blender_support.plan import manifest_from_plan, plan_scene
from skid.adapters.pid import render_pid
from skid.build import BOOTSTRAP, build_project, check_manifest, project_status, verify_bundle
from skid.core import apply_command, canonical_digest, load_document, save_document, validate_project

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "examples" / "pump_skid.json"
INJECTED_ERROR = {"code": "generation_failed", "severity": "error", "entity_ids": ["ent-pump"],
                  "message": "Injected adapter error"}
INJECTED_WARNING = {"code": "render_note", "severity": "warning", "entity_ids": ["ent-pump"],
                    "message": "Injected adapter warning"}


def runner_arguments(argv):
    """Parse a Blender argument array the way the bootstrap and ``run_build`` receive it."""
    assert argv[1:7] == ["--background", "--factory-startup", "--python-exit-code", "1", "--python", BOOTSTRAP], argv
    rest = argv[argv.index("--") + 1:]
    assert rest[0] == "build", rest
    parser = argparse.ArgumentParser()
    for name in ("--document", "--blend", "--manifest"):
        parser.add_argument(name, required=True)
    parser.add_argument("--preview")
    parser.add_argument("--select", nargs="*", default=[])
    return parser.parse_args(rest[1:])


class FakeBlender:
    """Stand-in for the Blender subprocess (not Blender): a plan-derived manifest and a placeholder blend file."""

    def __init__(self, code=0, tamper=None, write_blend=True, write_manifest=True, during=None, interrupt=None):
        self.code, self.tamper, self.during, self.interrupt = code, tamper, during, interrupt
        self.write_blend, self.write_manifest = write_blend, write_manifest
        self.calls = []

    def __call__(self, argv, timeout, cwd):
        self.calls.append(list(argv))
        args = runner_arguments(argv)
        if self.during:
            self.during()
        if self.interrupt:
            raise self.interrupt
        project = load_document(args.document)["current"]
        manifest = manifest_from_plan(plan_scene(project, tuple(args.select)))
        if self.tamper:
            manifest = self.tamper(copy.deepcopy(manifest))
        if self.write_blend:
            Path(args.blend).write_bytes(b"FAKE BLEND, not generated by Blender: " + project["id"].encode())
        if self.write_manifest:
            Path(args.manifest).write_text(json.dumps(manifest), encoding="utf-8")
        if args.preview:
            Path(args.preview).write_bytes(b"FAKE PNG")
        return self.code, "fake Blender output\n"


def with_diagnostic(record, **fields):
    """A ``FakeBlender`` tamper that appends ``record`` to the manifest's diagnostics and sets ``fields``."""
    def tamper(manifest):
        manifest["diagnostics"].append(copy.deepcopy(record))
        return dict(manifest, **fields)
    return tamper


def well_formed(diagnostic):
    return (isinstance(diagnostic, dict) and set(diagnostic) == {"code", "severity", "entity_ids", "message"}
            and isinstance(diagnostic["code"], str) and diagnostic["severity"] in ("error", "warning")
            and isinstance(diagnostic["entity_ids"], list) and all(isinstance(i, str) for i in diagnostic["entity_ids"])
            and isinstance(diagnostic["message"], str))


def edit(path, kind, payload):
    """Apply one command through the core and save it against the revision just read."""
    document = load_document(path)
    revision = document["current"]["revision"]
    command = {"id": f"cmd-test-{kind}-{revision}", "expected_revision": revision, "type": kind, "payload": payload}
    new, _ = apply_command(document, command)
    save_document(path, new, revision)
    return new


class BuildCase(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory(prefix="skid build ")
        self.dir = Path(self._tmp.name) / "my project"
        self.dir.mkdir()
        self.path = str(self.dir / "pump skid.json")
        save_document(self.path, load_document(FIXTURE), None)
        self.out = str(self.dir / "pump skid.skid")

    def tearDown(self):
        self._tmp.cleanup()

    def build(self, runner=None, **options):
        return build_project(self.path, self.out, runner=runner or FakeBlender(), **options)

    def rename(self, entity_id, tag):
        return edit(self.path, "rename_entity", {"entity_id": entity_id, "tag": tag})

    def pointer(self):
        return Path(self.out, "current.json").read_bytes()

    def listing(self, name):
        return sorted(os.listdir(Path(self.out, name)))

    def codes(self, report):
        return {d["code"] for d in report["diagnostics"]}


class AdapterFailureTest(BuildCase):
    def test_blender_failure_after_pid_success_keeps_the_published_bundle(self):
        first = self.build()
        self.assertEqual((first["outcome"], first["bundle_status"], first["requested_revision"]), ("published", "complete", 0))
        pointer, bundles = self.pointer(), self.listing("bundles")
        self.rename("ent-pump", "P-201")

        def failed(manifest):
            manifest["diagnostics"].append({"code": "build_failed", "severity": "error", "entity_ids": [],
                                            "message": "simulated Blender fault"})
            return dict(manifest, status="failed", representations={})

        report = self.build(FakeBlender(code=1, tamper=failed))
        self.assertEqual((report["outcome"], report["bundle"], report["requested_revision"]), ("failed", None, 1))
        self.assertLessEqual({"blender_exit_status", "adapter_failed", "build_failed"}, self.codes(report))
        self.assertEqual(self.pointer(), pointer)
        self.assertEqual(self.listing("bundles"), bundles)
        self.assertEqual(self.listing("staging"), [])
        self.assertEqual(verify_bundle(os.path.join(self.out, "bundles", bundles[0]))[1], [])

        status = project_status(self.path, self.out)
        self.assertEqual(status["state"], "stale")
        self.assertEqual((status["published"]["source_revision"], status["source"]["revision"]), (0, 1))
        self.assertEqual((status["last_build"]["outcome"], status["last_build"]["requested_revision"]), ("failed", 1))

    def test_exit_zero_needs_a_matching_manifest_and_artifact(self):
        def change(**fields):
            return lambda manifest: dict(manifest, **fields)

        def drop_entity(manifest):
            manifest["representations"].pop("ent-pump")
            return manifest

        cases = {
            "no manifest": (FakeBlender(write_manifest=False), "manifest_missing"),
            "no blend file": (FakeBlender(write_blend=False), "artifact_missing"),
            "other digest": (FakeBlender(tamper=change(input_digest="0" * 64)), "manifest_mismatch"),
            "other revision": (FakeBlender(tamper=change(source_revision=1)), "manifest_mismatch"),
            "boolean revision": (FakeBlender(tamper=change(source_revision=False)), "manifest_mismatch"),
            "other project": (FakeBlender(tamper=change(project_id="project-other")), "manifest_mismatch"),
            "other adapter": (FakeBlender(tamper=change(adapter="pid")), "manifest_mismatch"),
            "unsupported version": (FakeBlender(tamper=change(adapter_version="9.9.9")), "unsupported_adapter_version"),
            "failed status": (FakeBlender(tamper=change(status="failed")), "adapter_failed"),
            "unknown status": (FakeBlender(tamper=change(status="done")), "manifest_status"),
            "missing mapping": (FakeBlender(tamper=drop_entity), "mapping_incomplete"),
            "extra field": (FakeBlender(tamper=change(synchronized=True)), "manifest_fields"),
            "nonzero exit with a good manifest": (FakeBlender(code=1), "blender_exit_status"),
        }
        for label, (runner, code) in cases.items():
            with self.subTest(label):
                report = self.build(runner)
                self.assertEqual(report["outcome"], "failed")
                self.assertIn(code, self.codes(report))
                self.assertFalse(os.path.exists(os.path.join(self.out, "current.json")))
                self.assertEqual(self.listing("bundles"), [])
                self.assertEqual(self.listing("staging"), [])
                self.assertEqual(project_status(self.path, self.out)["state"], "unpublished")

    def test_pid_fault_or_mismatch_fails_before_blender_runs(self):
        from skid.adapters import pid

        real = pid.render_pid

        def wrong_revision(project, selected_ids=()):
            svg, manifest = real(project, selected_ids)
            return svg, dict(manifest, source_revision=manifest["source_revision"] + 1)

        def error_while_complete(project, selected_ids=()):
            svg, manifest = real(project, selected_ids)
            return svg, dict(manifest, diagnostics=[*manifest["diagnostics"], INJECTED_ERROR])

        for label, patch, code in (("fault", mock.patch.object(pid, "render_pid", side_effect=RuntimeError("boom")),
                                    "adapter_fault"),
                                   ("mismatch", mock.patch.object(pid, "render_pid", wrong_revision),
                                    "manifest_mismatch"),
                                   ("error while complete", mock.patch.object(pid, "render_pid", error_while_complete),
                                    "adapter_reported_error")):
            with self.subTest(label), patch:
                runner = FakeBlender()
                report = self.build(runner)
                self.assertEqual(report["outcome"], "failed")
                self.assertIn(code, self.codes(report))
                self.assertEqual(runner.calls, [])
                self.assertEqual(self.listing("staging"), [])

    def test_unknown_selection_is_rejected_before_generation(self):
        runner = FakeBlender()
        report = self.build(runner, selected_ids=("sym-pump",))
        self.assertEqual(report["outcome"], "failed")
        self.assertIn("selection_unknown_id", self.codes(report))
        self.assertEqual(runner.calls, [])


class ManifestDiagnosticsTest(BuildCase):
    def test_error_diagnostic_in_a_complete_manifest_is_not_published(self):
        report = self.build(FakeBlender(tamper=with_diagnostic(INJECTED_ERROR)))
        self.assertEqual((report["outcome"], report["bundle"], report["bundle_status"]), ("failed", None, None))
        self.assertIn("adapter_reported_error", self.codes(report))
        self.assertIn({"code": "generation_failed", "severity": "error", "entity_ids": ["ent-pump"],
                       "message": "Blender: Injected adapter error"}, report["diagnostics"])
        self.assertFalse(os.path.exists(os.path.join(self.out, "current.json")))
        self.assertEqual((self.listing("bundles"), self.listing("staging")), ([], []))
        self.assertEqual(project_status(self.path, self.out)["state"], "unpublished")

    def test_rejected_new_revision_keeps_the_published_bundle(self):
        self.build()
        pointer, bundles = self.pointer(), self.listing("bundles")
        self.rename("ent-pump", "P-201")
        cases = {
            "error while complete": (with_diagnostic(INJECTED_ERROR), {"adapter_reported_error", "generation_failed"}),
            "error while pending": (with_diagnostic(INJECTED_ERROR, status="pending"),
                                    {"adapter_reported_error", "generation_failed"}),
            "warning while complete": (with_diagnostic(INJECTED_WARNING), {"manifest_contradiction"}),
            "malformed record": (with_diagnostic(dict(INJECTED_WARNING, entity_ids="ent-pump"), status="pending"),
                                 {"diagnostics_invalid"}),
        }
        for label, (tamper, codes) in cases.items():
            with self.subTest(label):
                report = self.build(FakeBlender(tamper=tamper))
                self.assertEqual((report["outcome"], report["bundle"], report["requested_revision"]), ("failed", None, 1))
                self.assertLessEqual(codes, self.codes(report))
                self.assertEqual(self.pointer(), pointer)
                self.assertEqual(self.listing("bundles"), bundles)
                self.assertEqual(self.listing("staging"), [])
                self.assertEqual(verify_bundle(os.path.join(self.out, "bundles", bundles[0]))[1], [])
                status = project_status(self.path, self.out)
                self.assertEqual((status["state"], status["published"]["source_revision"], status["problems"]),
                                 ("stale", 0, []))

    def test_malformed_diagnostics_fail_with_structured_diagnostics(self):
        def replace(value):
            return lambda manifest: dict(manifest, diagnostics=value)

        cases = {
            "not a list": (replace(dict(INJECTED_WARNING)), "manifest_fields"),
            "not an object": (replace(["Injected adapter error"]), "diagnostics_invalid"),
            "missing field": (replace([{k: v for k, v in INJECTED_ERROR.items() if k != "message"}]),
                              "diagnostics_invalid"),
            "extra field": (replace([dict(INJECTED_WARNING, detail="x")]), "diagnostics_invalid"),
            "unknown severity": (replace([dict(INJECTED_WARNING, severity="fatal")]), "diagnostics_invalid"),
            "unhashable severity": (replace([dict(INJECTED_WARNING, severity=["error"])]), "diagnostics_invalid"),
            "entity_ids a string": (replace([dict(INJECTED_WARNING, entity_ids="ent-pump")]), "diagnostics_invalid"),
            "entity_ids with a number": (replace([dict(INJECTED_WARNING, entity_ids=["ent-pump", 7])]),
                                         "diagnostics_invalid"),
            "code not a string": (replace([dict(INJECTED_WARNING, code=None)]), "diagnostics_invalid"),
            "message not a string": (replace([dict(INJECTED_WARNING, message={"text": "x"})]), "diagnostics_invalid"),
            "malformed under failed status": (
                lambda manifest: dict(manifest, status="failed", representations={},
                                      diagnostics=[dict(INJECTED_ERROR, entity_ids={"ent-pump": 1})]),
                "diagnostics_invalid"),
        }
        for label, (tamper, code) in cases.items():
            with self.subTest(label):
                report = self.build(FakeBlender(tamper=tamper))
                self.assertEqual(report["outcome"], "failed")
                self.assertIn(code, self.codes(report))
                self.assertTrue(all(well_formed(d) for d in report["diagnostics"]), report["diagnostics"])
                self.assertFalse(os.path.exists(os.path.join(self.out, "current.json")))
                self.assertEqual((self.listing("bundles"), self.listing("staging")), ([], []))

    def test_pending_adapter_warning_is_reported_as_an_open_item(self):
        report = self.build(FakeBlender(tamper=with_diagnostic(INJECTED_WARNING, status="pending")))
        self.assertEqual((report["outcome"], report["bundle_status"], report["open_items"]),
                         ("published", "pending", [INJECTED_WARNING]))
        stored = json.loads(Path(self.out, "bundles", report["bundle"], "blender.manifest.json")
                            .read_text(encoding="utf-8"))
        self.assertEqual((stored["status"], stored["diagnostics"]), ("pending", [INJECTED_WARNING]))
        status = project_status(self.path, self.out)
        self.assertEqual((status["state"], status["problems"], status["open_items"]),
                         ("pending", [], [INJECTED_WARNING]))

    def test_pending_move_reports_model_and_adapter_warnings_once(self):
        placement = copy.deepcopy(load_document(self.path)["current"]["physical"]["placements"]["ent-pump"])
        placement["position_m"][0] += 0.5
        project = edit(self.path, "move_equipment", {"entity_id": "ent-pump", "placement": placement})["current"]
        report = self.build()
        self.assertEqual((report["outcome"], report["bundle_status"]), ("published", "pending"))
        model = [d for d in validate_project(project) if d["severity"] == "warning"]
        bundle = Path(self.out, "bundles", report["bundle"])
        manifests = {name: json.loads((bundle / f"{name}.manifest.json").read_text(encoding="utf-8"))
                     for name in ("pid", "blender")}
        reported = [d for manifest in manifests.values() for d in manifest["diagnostics"]]
        self.assertTrue(model and all(d in reported for d in model))  # the adapters repeat the model's warnings
        keys = [json.dumps(d, sort_keys=True) for d in report["open_items"]]
        self.assertEqual(len(keys), len(set(keys)))
        self.assertEqual(set(keys), {json.dumps(d, sort_keys=True) for d in model + reported})
        self.assertEqual(report["open_items"][:len(model)], model)
        self.assertTrue(any(d not in model for d in manifests["blender"]["diagnostics"]))  # 3D-specific items
        self.assertEqual(project_status(self.path, self.out)["open_items"], report["open_items"])


class ManifestCheckTest(unittest.TestCase):
    """The diagnostic rules hold for any adapter: here a real P&ID manifest checked directly."""

    def test_diagnostic_rules_for_a_pid_manifest(self):
        project = load_document(FIXTURE)["current"]
        digest = canonical_digest(project)
        svg, manifest = render_pid(project)
        with tempfile.TemporaryDirectory(prefix="skid manifest ") as tmp:
            artifact = os.path.join(tmp, "pid.svg")
            Path(artifact).write_text(svg, encoding="utf-8")
            self.assertEqual((manifest["status"], check_manifest(manifest, "pid", project, digest, artifact)),
                             ("complete", []))
            cases = {
                "error while complete": (dict(manifest, diagnostics=[INJECTED_ERROR]),
                                         {"adapter_reported_error", "generation_failed"}),
                "error while pending": (dict(manifest, status="pending", diagnostics=[INJECTED_WARNING, INJECTED_ERROR]),
                                        {"adapter_reported_error", "generation_failed"}),
                "warning while complete": (dict(manifest, diagnostics=[INJECTED_WARNING]), {"manifest_contradiction"}),
                "warning while pending": (dict(manifest, status="pending", diagnostics=[INJECTED_WARNING]), set()),
                "malformed record": (dict(manifest, status="pending", diagnostics=[dict(INJECTED_WARNING, code="")]),
                                     {"diagnostics_invalid"}),
            }
            for label, (candidate, codes) in cases.items():
                with self.subTest(label):
                    before = copy.deepcopy(candidate)
                    problems = check_manifest(candidate, "pid", project, digest, artifact)
                    self.assertEqual({d["code"] for d in problems}, codes)
                    self.assertTrue(all(well_formed(d) for d in problems), problems)
                    self.assertEqual(candidate, before)


class RecoveryTest(BuildCase):
    def test_source_change_during_the_build_is_not_published(self):
        self.build()
        pointer, bundles = self.pointer(), self.listing("bundles")
        self.rename("ent-tank", "TK-201")
        report = self.build(FakeBlender(during=lambda: self.rename("ent-pump", "P-201")))
        self.assertEqual((report["outcome"], report["requested_revision"], report["bundle"]), ("superseded", 1, None))
        self.assertIn("source_changed", self.codes(report))
        self.assertEqual(self.pointer(), pointer)
        self.assertEqual(self.listing("bundles"), bundles)
        self.assertEqual(self.listing("staging"), [])
        status = project_status(self.path, self.out)
        self.assertEqual((status["state"], status["source"]["revision"], status["published"]["source_revision"]),
                         ("stale", 2, 0))
        self.assertEqual(status["last_build"]["outcome"], "superseded")

        again = self.build()
        self.assertEqual((again["outcome"], again["requested_revision"]), ("published", 2))
        self.assertEqual(project_status(self.path, self.out)["state"], "synchronized")

    def test_interrupted_build_leaves_a_valid_pointer(self):
        self.build()
        pointer = self.pointer()
        self.rename("ent-pump", "P-201")
        with self.assertRaises(KeyboardInterrupt):
            self.build(FakeBlender(interrupt=KeyboardInterrupt()))
        self.assertEqual(self.pointer(), pointer)
        self.assertEqual(self.listing("staging"), [])
        status = project_status(self.path, self.out)
        self.assertEqual((status["state"], status["problems"]), ("stale", []))
        self.assertEqual(status["last_build"]["outcome"], "interrupted")

    def test_unchanged_rebuild_reuses_the_bundle_and_selection_gets_its_own(self):
        runner = FakeBlender()
        first = self.build(runner)
        pointer = self.pointer()
        second = self.build(runner)
        self.assertEqual((second["outcome"], second["bundle"], len(runner.calls)), ("unchanged", first["bundle"], 1))
        self.assertEqual(self.pointer(), pointer)

        selected = self.build(runner, selected_ids=("ent-pump",))
        self.assertEqual((selected["outcome"], selected["requested_revision"], len(runner.calls)), ("published", 0, 2))
        self.assertNotEqual(selected["bundle"], first["bundle"])
        svg = {r["bundle"]: Path(self.out, "bundles", r["bundle"], "pid.svg").read_bytes() for r in (first, selected)}
        self.assertNotEqual(svg[first["bundle"]], svg[selected["bundle"]])
        self.assertEqual(project_status(self.path, self.out)["published"]["selected_ids"], ["ent-pump"])

        back = self.build(runner)
        self.assertEqual((back["outcome"], back["bundle"], back["reused"], len(runner.calls)),
                         ("published", first["bundle"], True, 2))
        self.assertEqual(self.listing("bundles"), sorted([first["bundle"], selected["bundle"]]))

    def test_tampered_bundle_is_reported_and_not_reused(self):
        first = self.build()
        svg = Path(self.out, "bundles", first["bundle"], "pid.svg")
        svg.write_bytes(svg.read_bytes() + b"<!-- edited -->")
        status = project_status(self.path, self.out)
        self.assertEqual(status["state"], "bundle_invalid")
        self.assertIn("bundle_file_changed", {d["code"] for d in status["problems"]})
        report = self.build()
        self.assertEqual(report["outcome"], "failed")
        self.assertIn("bundle_unverifiable", self.codes(report))
        self.assertTrue(svg.exists())

    def test_foreign_output_directory_is_refused(self):
        foreign = self.dir / "my documents"
        foreign.mkdir()
        (foreign / "current.json").write_text("my own file", encoding="utf-8")
        report = build_project(self.path, foreign, runner=FakeBlender())
        self.assertEqual(report["outcome"], "failed")
        self.assertIn("output_not_owned", self.codes(report))
        self.assertEqual(sorted(os.listdir(foreign)), ["current.json"])
        self.assertEqual((foreign / "current.json").read_text(encoding="utf-8"), "my own file")

    def test_concurrent_build_is_refused_and_leftovers_are_kept(self):
        self.build()
        os.makedirs(os.path.join(self.out, "staging", "left-by-a-killed-build"))
        with open(os.path.join(self.out, ".build.lock"), "a+") as handle:
            fcntl.flock(handle.fileno(), fcntl.LOCK_EX)
            report = self.build()
            fcntl.flock(handle.fileno(), fcntl.LOCK_UN)
        self.assertEqual(report["outcome"], "failed")
        self.assertIn("build_busy", self.codes(report))
        self.assertEqual(self.build()["outcome"], "unchanged")
        self.assertEqual(self.listing("staging"), ["left-by-a-killed-build"])
        self.assertEqual(project_status(self.path, self.out)["staging"], ["left-by-a-killed-build"])


